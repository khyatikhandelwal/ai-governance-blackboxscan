"""
Stable Signature Watermark Detector
Detects and validates watermarks in images generated by watermarked models.
"""

import torch
import torch.nn as nn
from PIL import Image
import numpy as np
from torchvision import transforms
from scipy import special
import os

# Default watermark key (48 bits)
DEFAULT_KEY = '111010110101000001010111010011010100010000100111'


class WatermarkExtractor(nn.Module):
    """Pre-trained watermark extractor based on HiDDeN architecture"""
    def __init__(self, num_bits=48):
        super().__init__()
        self.num_bits = num_bits
        
        # Extractor network (7 conv blocks)
        layers = []
        in_channels = 3
        for i in range(7):
            layers.extend([
                nn.Conv2d(in_channels, 64, kernel_size=3, stride=1, padding=1),
                nn.BatchNorm2d(64),
                nn.ReLU(inplace=True)
            ])
            in_channels = 64
        
        # Final layer to extract bits
        layers.extend([
            nn.Conv2d(64, num_bits, kernel_size=3, stride=1, padding=1),
            nn.AdaptiveAvgPool2d(1)
        ])
        
        self.extractor = nn.Sequential(*layers)
        self.fc = nn.Linear(num_bits, num_bits)
    
    def forward(self, x):
        x = self.extractor(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return torch.sigmoid(x)


class WatermarkDetector:
    """Detector for Stable Signature watermarks"""
    
    def __init__(self, watermark_key=DEFAULT_KEY, device='cuda', extractor_path=None):
        self.device = device
        self.watermark_key = watermark_key
        self.num_bits = len(watermark_key)
        
        # Convert key to tensor
        self.key_tensor = torch.tensor(
            [int(b) for b in watermark_key], 
            dtype=torch.float32
        ).to(device)
        
        # Initialize extractor
        print(f"Initializing watermark extractor ({self.num_bits} bits)")
        self.extractor = WatermarkExtractor(num_bits=self.num_bits).to(device)
        
        # Load pre-trained weights if provided
        if extractor_path:
            self.load_extractor_weights(extractor_path)
        else:
            self._init_extractor_weights()
        
        self.extractor.eval()
        
        # Image preprocessing
        self.transform = transforms.Compose([
            transforms.Resize((512, 512)),
            transforms.ToTensor(),
        ])
    
    def _init_extractor_weights(self):
        """Initialize extractor with random weights (in practice, use pre-trained)"""
        for m in self.extractor.modules():
            if isinstance(m, nn.Conv2d):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
            elif isinstance(m, nn.BatchNorm2d):
                nn.init.constant_(m.weight, 1)
                nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.Linear):
                nn.init.normal_(m.weight, 0, 0.01)
                nn.init.constant_(m.bias, 0)
    
    def load_extractor_weights(self, extractor_path):
        """Load pre-trained extractor weights"""
        print(f"Loading extractor from {extractor_path}")
        if extractor_path.endswith('.torchscript.pt'):
            self.extractor = torch.jit.load(extractor_path).to(self.device)
        else:
            state_dict = torch.load(extractor_path, map_location=self.device)
            self.extractor.load_state_dict(state_dict)
        self.extractor.eval()
    
    def load_image(self, image_path):
        """Load and preprocess image"""
        image = Image.open(image_path).convert('RGB')
        image_tensor = self.transform(image).unsqueeze(0).to(self.device)
        return image_tensor
    
    def extract_message(self, image_tensor):
        """Extract watermark message from image"""
        with torch.no_grad():
            # Extract continuous values
            extracted = self.extractor(image_tensor)
            # Convert to binary
            extracted_binary = (extracted > 0.5).float()
        return extracted, extracted_binary
    
    def compute_bit_accuracy(self, extracted_msg, target_msg):
        """Compute bit accuracy between extracted and target message"""
        matching_bits = (extracted_msg == target_msg).float().sum().item()
        total_bits = target_msg.numel()
        accuracy = matching_bits / total_bits
        return accuracy, int(matching_bits)
    
    def statistical_test(self, num_matching_bits, significance_level=1e-6):
        """
        Perform statistical hypothesis test for watermark detection
        
        H0: Image is NOT watermarked (random bits)
        H1: Image IS watermarked
        
        Returns:
            is_watermarked: bool
            p_value: float
            threshold: int (minimum matching bits needed)
        """
        k = self.num_bits
        
        # Under H0, each bit matches with probability 0.5
        # Number of matching bits follows Binomial(k, 0.5)
        # We use the regularized incomplete beta function for p-value
        
        # Calculate p-value: P(M >= num_matching_bits | H0)
        # This is 1 - CDF(num_matching_bits - 1)
        p_value = special.betainc(num_matching_bits, k - num_matching_bits + 1, 0.5)
        
        # Find threshold for given significance level
        threshold = k // 2  # Start from middle
        for tau in range(k // 2, k + 1):
            fpr = special.betainc(tau + 1, k - tau, 0.5)
            if fpr <= significance_level:
                threshold = tau
                break
        
        is_watermarked = num_matching_bits >= threshold
        
        return is_watermarked, p_value, threshold
    
    def detect(self, image_path, significance_level=1e-6, verbose=True):
        """
        Detect watermark in an image
        
        Args:
            image_path: Path to image file
            significance_level: Significance level for statistical test (default: 1e-6)
            verbose: Print detailed results
        
        Returns:
            dict with detection results
        """
        if verbose:
            print("\n" + "="*60)
            print("Watermark Detection")
            print("="*60)
            print(f"Image: {image_path}")
            print(f"Expected key: {self.watermark_key}")
        
        # Load image
        image_tensor = self.load_image(image_path)
        
        # Extract message
        extracted_continuous, extracted_binary = self.extract_message(image_tensor)
        
        # Convert to string for display
        extracted_binary_cpu = extracted_binary.cpu().squeeze()
        extracted_str = ''.join([str(int(b)) for b in extracted_binary_cpu])
        
        # Compute bit accuracy
        target_msg = self.key_tensor.unsqueeze(0)
        accuracy, num_matching = self.compute_bit_accuracy(extracted_binary, target_msg)
        
        # Statistical test
        is_watermarked, p_value, threshold = self.statistical_test(
            num_matching, 
            significance_level
        )
        
        # Prepare results
        results = {
            'image_path': image_path,
            'is_watermarked': is_watermarked,
            'extracted_message': extracted_str,
            'expected_message': self.watermark_key,
            'bit_accuracy': accuracy,
            'matching_bits': num_matching,
            'total_bits': self.num_bits,
            'p_value': p_value,
            'threshold_bits': threshold,
            'significance_level': significance_level,
            'confidence': 1 - p_value if is_watermarked else p_value
        }
        
        if verbose:
            print(f"\nExtracted message: {extracted_str}")
            print(f"Expected message:  {self.watermark_key}")
            print(f"\nBit accuracy: {accuracy:.2%} ({num_matching}/{self.num_bits} bits match)")
            print(f"Detection threshold: {threshold} bits (α = {significance_level})")
            print(f"P-value: {p_value:.2e}")
            print(f"\n{'='*60}")
            
            if is_watermarked:
                print(f"✓ WATERMARK DETECTED (confidence: {results['confidence']:.4%})")
            else:
                print(f"✗ NO WATERMARK DETECTED")
            
            print("="*60 + "\n")
        
        return results
    
    def batch_detect(self, image_paths, significance_level=1e-6):
        """Detect watermarks in multiple images"""
        results = []
        
        print(f"\nProcessing {len(image_paths)} images...")
        for img_path in image_paths:
            result = self.detect(img_path, significance_level, verbose=False)
            results.append(result)
        
        # Summary
        watermarked_count = sum(1 for r in results if r['is_watermarked'])
        avg_accuracy = np.mean([r['bit_accuracy'] for r in results])
        
        print("\n" + "="*60)
        print("Batch Detection Summary")
        print("="*60)
        print(f"Total images: {len(image_paths)}")
        print(f"Watermarked: {watermarked_count}")
        print(f"Not watermarked: {len(image_paths) - watermarked_count}")
        print(f"Average bit accuracy: {avg_accuracy:.2%}")
        print("="*60 + "\n")
        
        return results


def main():
    """Example usage"""
    import argparse
    
    parser = argparse.ArgumentParser(description='Detect Stable Signature watermarks in images')
    parser.add_argument('--image', type=str, help='Path to single image file')
    parser.add_argument('--image_dir', type=str, help='Directory containing images')
    parser.add_argument('--watermark_key', type=str, default=DEFAULT_KEY,
                       help='48-bit binary watermark key')
    parser.add_argument('--key_file', type=str, help='Path to file containing watermark key')
    parser.add_argument('--extractor_path', type=str, default=None,
                       help='Path to pre-trained extractor weights')
    parser.add_argument('--significance_level', type=float, default=1e-6,
                       help='Significance level for detection (default: 1e-6)')
    parser.add_argument('--device', type=str, default='cuda',
                       help='Device to use (cuda/cpu)')
    
    args = parser.parse_args()
    
    # Load watermark key
    if args.key_file:
        with open(args.key_file, 'r') as f:
            watermark_key = f.read().strip()
    else:
        watermark_key = args.watermark_key
    
    # Initialize detector
    detector = WatermarkDetector(
        watermark_key=watermark_key,
        device=args.device,
        extractor_path=args.extractor_path
    )
    
    # Detect watermark
    if args.image:
        # Single image
        results = detector.detect(args.image, args.significance_level)
        
    elif args.image_dir:
        # Multiple images
        image_paths = [
            os.path.join(args.image_dir, f) 
            for f in os.listdir(args.image_dir)
            if f.lower().endswith(('.png', '.jpg', '.jpeg'))
        ]
        results = detector.batch_detect(image_paths, args.significance_level)
        
        # Save results to CSV
        import csv
        output_file = 'detection_results.csv'
        with open(output_file, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=results[0].keys())
            writer.writeheader()
            writer.writerows(results)
        print(f"Results saved to {output_file}")
    
    else:
        parser.print_help()


if __name__ == '__main__':
    main()